/* ===========================================================================
 * 查詢工具
 * =========================================================================*/

const CARD_MAP = new Map(KNOWLEDGE_CARDS.map((c) => [c.id, c]));

/** 依 ID 取得知識卡 */
export function getKnowledgeCard(id: string): KnowledgeCard | undefined {
  return CARD_MAP.get(id);
}

/** 依主題篩選知識卡；傳入 null 代表全部 */
export function getCardsByTopic(topic: string | null): KnowledgeCard[] {
  if (!topic) return KNOWLEDGE_CARDS;
  return KNOWLEDGE_CARDS.filter((c) => c.topic === topic);
}

/** 依主題篩選測驗題；傳入 null 代表全部 */
export function getQuestionsByTopic(topic: string | null): QuizQuestion[] {
  if (!topic) return QUIZ_QUESTIONS;
  return QUIZ_QUESTIONS.filter((q) => q.topic === topic);
}
